#int data type
x = 5
print(x)

#string data type
x = "John"
print(x)


#float data type
x = 5
print(x)

#complex data type
x = 5j
print(complex(x))

#list data type
x = ["apple","banana","cherry"]
print(list(x))

#tuple data type
x = ("apple","banana","cherry")
print(tuple(x))

#range data type
x = range(5)
print(x)

#dict data type
x = {"name" : "John", "age" : 36}
print(dict(x))

#set data type
x = {"apple","banana","cherry"}
print(set(x))

#frozenset data type
x = ({"apple","banana","cherry"})
print(frozenset(x))

#bool data type
x = True
print(bool(x))

#bytes data type
x = b"hello"
print(bytes(x))

#bytesarray data type
x = bytearray(5)
print(x)

#memoryview data type
x = memoryview(bytes(5))
print(x)








